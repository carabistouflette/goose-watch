#!/usr/bin/env python3
"""Fingerprint native sources so Goose's local package cache rebuilds them."""
# SPDX-License-Identifier: Apache-2.0
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    digest = hashlib.sha256()
    paths = [Path(__file__).resolve()]
    paths += [p for p in (ROOT / 'native').rglob('*') if p.is_file()]
    for path in sorted(paths):
        name = path.relative_to(ROOT).as_posix().encode()
        data = path.read_bytes()
        digest.update(len(name).to_bytes(8, 'big') + name)
        digest.update(len(data).to_bytes(8, 'big') + data)
    text = ('c_sources = ["native/watch.c", "native/set.c"];\n'
            'c_flags_cc = ["-std=c11", "-Wall", "-Wextra", "-Werror"];\n'
            'exclude = [".toolchain", ".build", "bench", "tests", "examples"];\n\n'
            '// Generated by scripts/native-manifest.py; refresh with make format.\n'
            f'// Source SHA256: {digest.hexdigest()}\n')
    target = ROOT / 'watch.build'
    if args.check:
        if not target.exists() or target.read_text() != text:
            parser.exit(1, 'Native source fingerprint is stale; run make format.\n')
    else:
        target.write_text(text)


if __name__ == '__main__':
    main()
